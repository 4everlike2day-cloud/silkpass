export const LANGS = ['en', 'ru', 'uz'] as const
export type Lang = (typeof LANGS)[number]
export const LANG_LABEL: Record<Lang, string> = {en: 'EN', ru: 'RU', uz: 'UZ'}

/** Адрес страницы на нужном языке: href('ru', '/shop') -> '/ru/shop'. */
export function href(lang: Lang, path: string) {
  if (lang === 'en') return path
  return path === '/' ? `/${lang}` : `/${lang}${path}`
}

/** Язык и путь без префикса из адреса страницы. */
export function splitPath(raw: string): {lang: Lang; path: string} {
  // /ru.html и /ru/index.html тоже считаем /ru (на случай прямых ссылок на файлы)
  const pathname = raw.replace(/\/index\.html$/, '/').replace(/\.html$/, '').replace(/(.)\/$/, '$1')
  const m = pathname.match(/^\/(ru|uz)(?=\/|$)/)
  if (!m) return {lang: 'en', path: pathname || '/'}
  const rest = pathname.slice(m[0].length) || '/'
  return {lang: m[1] as Lang, path: rest}
}

